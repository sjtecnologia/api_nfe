import json
import psycopg2
from psycopg2 import Error
from datetime import datetime

def import_ncm_data(json_file_path, db_config):
    """
    Importa dados NCM de um arquivo JSON para a tabela 'ncms' no PostgreSQL.

    Args:
        json_file_path (str): Caminho para o arquivo JSON contendo os dados NCM.
        db_config (dict): Dicionário com as configurações de conexão ao banco de dados.
                          Ex: {'host': 'localhost', 'database': 'seu_banco',
                               'user': 'seu_usuario', 'password': 'sua_senha'}
    """
    conn = None
    try:
        # Conectar ao banco de dados PostgreSQL
        print("Conectando ao banco de dados PostgreSQL...")
        conn = psycopg2.connect(**db_config)
        cursor = conn.cursor()
        print("Conexão bem-sucedida.")

        # Abrir e carregar o arquivo JSON
        print(f"Lendo o arquivo JSON: {json_file_path}...")
        with open(json_file_path, 'r', encoding='utf-8') as f:
            ncm_records = json.load(f)
        print(f"Total de {len(ncm_records)} registros encontrados no JSON.")

        # Consulta SQL para inserção/atualização de dados
        # A coluna ncm_id é GENERATED BY DEFAULT AS IDENTITY e será preenchida automaticamente.
        # Usamos ON CONFLICT (codigo) DO UPDATE para lidar com duplicatas com base na UNIQUE CONSTRAINT.
        insert_sql = """
        INSERT INTO ncms (codigo, descricao, "data_Fim", "data_Inicio", tipo_ato, numero_ato, ano_ato)
        VALUES (%s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT (codigo) DO UPDATE SET
            descricao = EXCLUDED.descricao,
            "data_Fim" = EXCLUDED."data_Fim",
            "data_Inicio" = EXCLUDED."data_Inicio",
            tipo_ato = EXCLUDED.tipo_ato,
            numero_ato = EXCLUDED.numero_ato,
            ano_ato = EXCLUDED.ano_ato;
        """

        # Inserir cada registro no banco de dados
        print("Iniciando a importação dos dados...")
        for record in ncm_records:
            # Mapeamento dos campos do JSON para as colunas do banco de dados
            codigo = record.get('codigo')
            descricao = record.get('descricao')
            
            # Tratamento e conversão de datas (assumindo formato DD/MM/YYYY do JSON)
            data_inicio_str = record.get('data_Inicio')
            data_fim_str = record.get('data_Fim')

            data_Inicio = None
            if data_inicio_str:
                try:
                    data_Inicio = datetime.strptime(data_inicio_str, '%d/%m/%Y')
                except ValueError:
                    print(f"Aviso: Não foi possível parsear Data_Inicio '{data_inicio_str}' para o código {codigo}. Será importado como NULL.")

            data_fim = None
            if data_fim_str:
                try:
                    data_fim = datetime.strptime(data_fim_str, '%d/%m/%Y')
                except ValueError:
                    print(f"Aviso: Não foi possível parsear Data_Fim '{data_fim_str}' para o código {codigo}. Será importado como NULL.")
            
            tipo_ato = record.get('tipo_ato')
            numero_ato = record.get('numero_ato')
            ano_ato = record.get('ano_ato')

            # Executar a inserção
            cursor.execute(insert_sql, (codigo, descricao, data_fim, data_Inicio, tipo_ato, numero_ato, ano_ato))
        
        # Commit das transações
        conn.commit()
        print("Importação de NCM concluída com sucesso!")

    except (Exception, Error) as error:
        print(f"Erro ao importar dados NCM: {error}")
        if conn:
            conn.rollback()  # Reverter em caso de erro
    finally:
        if conn:
            cursor.close()
            conn.close()
            print("Conexão ao banco de dados PostgreSQL fechada.")

