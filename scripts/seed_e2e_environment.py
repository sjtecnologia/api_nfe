#!/usr/bin/env python3
"""Cria um ambiente E2E local e isolado para a Fase 4.6F.

Uso seguro: DATABASE_URL deve apontar para PostgreSQL local com database cujo
nome comece por ``e2e_``. A senha é lida de E2E_PASSWORD e nunca é exibida.
"""
from __future__ import annotations

import os
import sys
from datetime import datetime, timedelta
from decimal import Decimal
from urllib.parse import urlsplit

from werkzeug.security import generate_password_hash
from sqlalchemy import create_engine, text

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

DATABASE_URL = os.environ.get("DATABASE_URL", "")
ENVIRONMENT = os.environ.get("ENVIRONMENT", os.environ.get("FLASK_ENV", "development")).lower()
parsed = urlsplit(DATABASE_URL)
database_name = (parsed.path or "").strip("/")

if ENVIRONMENT == "production" or os.environ.get("FLASK_ENV", "").lower() == "production":
    raise SystemExit("E2E_SEED_REFUSED_IN_PRODUCTION")
if parsed.scheme not in {"postgresql", "postgres"} or parsed.hostname not in {"localhost", "127.0.0.1"}:
    raise SystemExit("E2E_SEED_REFUSED_NONLOCAL_DATABASE")
if not database_name.startswith(("e2e_", "billing_reservation_")):
    raise SystemExit("E2E_SEED_REFUSED_UNSAFE_DATABASE_NAME")

username = os.environ.get("E2E_USERNAME", "e2e@emitemax.test")
password = os.environ.get("E2E_PASSWORD")
if not password:
    raise SystemExit("E2E_PASSWORD_REQUIRED_IN_MEMORY")

from database.models import Base, Cliente, RegimeTributario, Role, UserClient, UserModel, UserRole
from database.billing_shadow_models import (
    BillingAccount,
    BillingPlan,
    BillingPlanVersion,
    BillingSubscription,
    BillingSubscriptionCompany,
)
from database.billing_usage_models import BillingUsageCounter, BillingUsageEvent, BillingUsageReservation

engine = create_engine(DATABASE_URL)
Base.metadata.create_all(bind=engine)

period_start = datetime.utcnow().date().replace(day=1)
period_end = (period_start.replace(day=28) + timedelta(days=4)).replace(day=1)
usage = int(os.environ.get("E2E_BILLING_USAGE", "0"))
if usage not in {0, 49, 50}:
    raise SystemExit("E2E_BILLING_USAGE deve ser 0, 49 ou 50")

with engine.begin() as db:
    db.execute(text("""
        CREATE TABLE IF NOT EXISTS nfse (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            cliente_id INTEGER,
            numero_rps INTEGER,
            status VARCHAR(30),
            data_emissao TIMESTAMP,
            protocolo VARCHAR(255),
            mensagem_retorno VARCHAR(255),
            tomador_razao_social VARCHAR(255),
            tomador_cpf_cnpj VARCHAR(20),
            valor_servicos NUMERIC(12, 2)
        )
    """))
    for column, definition in {
        "numero_rps": "INTEGER", "status": "VARCHAR(30)", "data_emissao": "TIMESTAMP",
        "protocolo": "VARCHAR(255)", "mensagem_retorno": "VARCHAR(255)",
        "tomador_razao_social": "VARCHAR(255)", "tomador_cpf_cnpj": "VARCHAR(20)",
        "valor_servicos": "NUMERIC(12, 2)",
    }.items():
        db.execute(text(f"ALTER TABLE nfse ADD COLUMN IF NOT EXISTS {column} {definition}"))
    db.execute(text("""
        CREATE OR REPLACE FUNCTION get_proximo_numero_nfe(p_cliente_id INTEGER, p_modelo VARCHAR, p_serie INTEGER)
        RETURNS INTEGER
        LANGUAGE SQL
        AS $$
            SELECT COALESCE(MAX(numero), 0) + 1
            FROM nfe_emitidas
            WHERE cliente_id = p_cliente_id AND modelo = p_modelo AND serie = p_serie
        $$
    """))
    user_active_column = db.execute(text("""
        SELECT column_name FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'users'
          AND column_name IN ('is_active', '_is_active')
        ORDER BY CASE column_name WHEN 'is_active' THEN 1 ELSE 2 END
        LIMIT 1
    """)).scalar()
    if user_active_column is None:
        raise SystemExit("E2E_SEED_USERS_SCHEMA_UNSUPPORTED")
    regime = db.execute(text("SELECT regime_tributario_id FROM regimes_tributarios WHERE nome = :nome"), {"nome": "Simples Nacional"}).scalar()
    if regime is None:
        regime = db.execute(text("INSERT INTO regimes_tributarios (nome, crt) VALUES ('Simples Nacional', 1) RETURNING regime_tributario_id")).scalar()

    cliente = db.execute(text("SELECT cliente_id FROM clientes WHERE cnpj = :cnpj"), {"cnpj": "11222333000181"}).scalar()
    if cliente is None:
        cliente = db.execute(text("""
            INSERT INTO clientes
                (cnpj, produtor_rural, razao_social, nome_fantasia, regime_tributario_id,
                 cnae, logradouro, numero, bairro, codigo_municipio, nome_municipio, uf,
                 cep, ambiente, ativo, data_cadastro, data_atualizacao)
            VALUES
                ('11222333000181', FALSE, 'EMITEMAX E2E HOMOLOGACAO', 'EMITEMAX E2E', :regime,
                 '4781100', 'Rua E2E', '100', 'Centro', '3550308', 'Sao Paulo', 'SP',
                 '01000000', 2, TRUE, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
            RETURNING cliente_id
        """), {"regime": regime}).scalar()

    role = db.execute(text("SELECT id FROM roles WHERE name = 'Editor'"), {}).scalar()
    if role is None:
        role = db.execute(text("INSERT INTO roles (name, description) VALUES ('Editor', 'E2E operator') RETURNING id")).scalar()

    user = db.execute(text("SELECT id FROM users WHERE username = :username"), {"username": username}).scalar()
    if user is None:
        user = db.execute(text("""
            INSERT INTO users (username, password_hash, email, {active_column}, created_at)
            VALUES (:username, :password_hash, :email, TRUE, CURRENT_TIMESTAMP)
            RETURNING id
        """.format(active_column=user_active_column)), {"username": username, "password_hash": generate_password_hash(password), "email": username}).scalar()
    else:
        db.execute(text(f"UPDATE users SET password_hash = :password_hash, {user_active_column} = TRUE WHERE id = :user_id"), {"password_hash": generate_password_hash(password), "user_id": user})

    db.execute(text("INSERT INTO user_roles (user_id, role_id) VALUES (:user, :role) ON CONFLICT DO NOTHING"), {"user": user, "role": role})
    db.execute(text("INSERT INTO user_clients (user_id, client_id) VALUES (:user, :client) ON CONFLICT DO NOTHING"), {"user": user, "client": cliente})

    plan = db.execute(text("SELECT plan_id FROM billing_plans WHERE code = 'START_V1'"), {}).scalar()
    if plan is None:
        plan = db.execute(text("INSERT INTO billing_plans (code, name, active, display_order) VALUES ('START_V1', 'Start E2E', TRUE, 1) RETURNING plan_id")).scalar()
    version = db.execute(text("SELECT plan_version_id FROM billing_plan_versions WHERE version_code = 'START_V1'"), {}).scalar()
    if version is None:
        version = db.execute(text("""
            INSERT INTO billing_plan_versions (plan_id, version_code, price, currency, valid_from, status, created_at)
            VALUES (:plan, 'START_V1', 60.00, 'BRL', CURRENT_TIMESTAMP, 'ACTIVE', CURRENT_TIMESTAMP)
            RETURNING plan_version_id
        """), {"plan": plan}).scalar()

    account = db.execute(text("SELECT account_id FROM billing_accounts WHERE name = 'EMITEMAX E2E ACCOUNT'"), {}).scalar()
    if account is None:
        account = db.execute(text("INSERT INTO billing_accounts (name, status, created_at, updated_at) VALUES ('EMITEMAX E2E ACCOUNT', 'ACTIVE', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP) RETURNING account_id")).scalar()
    subscription = db.execute(text("SELECT subscription_id FROM billing_subscriptions WHERE account_id = :account AND plan_version_id = :version"), {"account": account, "version": version}).scalar()
    if subscription is None:
        subscription = db.execute(text("""
            INSERT INTO billing_subscriptions
                (account_id, plan_version_id, status, contracted_price, currency, started_at, billing_cycle, created_at, updated_at)
            VALUES (:account, :version, 'ACTIVE', 60.00, 'BRL', CURRENT_TIMESTAMP, 'MONTHLY', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
            RETURNING subscription_id
        """), {"account": account, "version": version}).scalar()
    db.execute(text("INSERT INTO billing_subscription_companies (subscription_id, cliente_id, status, linked_at) VALUES (:subscription, :client, 'ACTIVE', CURRENT_TIMESTAMP) ON CONFLICT DO NOTHING"), {"subscription": subscription, "client": cliente})

    db.execute(text("DELETE FROM billing_usage_reservations WHERE subscription_id = :subscription"), {"subscription": subscription})
    db.execute(text("DELETE FROM billing_usage_events WHERE subscription_id = :subscription"), {"subscription": subscription})
    db.execute(text("""
        INSERT INTO billing_usage_counters (subscription_id, metric_key, period_start, period_end, quantity, version, updated_at)
        VALUES (:subscription, 'NFE_ISSUED', :start, :end, :usage, 1, CURRENT_TIMESTAMP)
        ON CONFLICT (subscription_id, metric_key, period_start, period_end)
        DO UPDATE SET quantity = EXCLUDED.quantity, version = billing_usage_counters.version + 1, updated_at = CURRENT_TIMESTAMP
    """), {"subscription": subscription, "start": period_start, "end": period_end, "usage": usage})

print(f"E2E_SEED=PASS")
print(f"E2E_USER=READY id={user}")
print(f"E2E_TENANT=READY id={cliente}")
print(f"E2E_SUBSCRIPTION=START_V1 id={subscription}")
print(f"E2E_BILLING_USAGE={usage}/50")
print(f"BILLING_NFE_QUOTA_ROLLOUT_CLIENT_IDS={cliente}")
