# Set de todos os códigos válidos (excluindo SEM CBENEF)
CODIGOS_VALIDOS_SP = frozenset(k for k in TABELA_CBENEF_SP if k != 'SEM CBENEF')

# Índice invertido: CST -> lista de códigos válidos
_IDX_CST: dict[str, list[str]] = {}
for _cod, _dados in TABELA_CBENEF_SP.items():
    if _cod == 'SEM CBENEF':
        continue
    for _cst in _dados['csts']:
        _IDX_CST.setdefault(_cst, []).append(_cod)


def codigos_para_cst(cst: str) -> list[dict]:
    """Retorna lista de {codigo, descricao, dispositivo} válidos para o CST informado."""
    cst_norm = str(cst).strip().zfill(2)
    return [
        {
            'codigo': cod,
            'descricao': TABELA_CBENEF_SP[cod]['descricao'],
            'dispositivo': TABELA_CBENEF_SP[cod]['dispositivo'],
            'obs': TABELA_CBENEF_SP[cod]['obs'],
        }
        for cod in _IDX_CST.get(cst_norm, [])
    ]


def validar_cbenef_para_cst(codigo: str, cst: str) -> tuple[bool, str]:
    """
    Valida se o código cBenef é adequado para o CST informado.
    Retorna (ok, mensagem_erro).
    """
    codigo = str(codigo).strip().upper()
    cst_norm = str(cst).strip().zfill(2)
    if codigo not in TABELA_CBENEF_SP:
        return False, f"Código cBenef '{codigo}' não consta na tabela oficial SP."
    dados = TABELA_CBENEF_SP[codigo]
    if cst_norm not in dados['csts']:
        return False, (
            f"Código cBenef '{codigo}' não é válido para CST {cst_norm}. "
            f"CSTs suportados: {', '.join(dados['csts'])}. "
            f"Benefício: {dados['descricao'][:80]}"
        )
    return True, ''